// 키릴 문자 → 로마자 (러시아어·카자흐어 이름을 읽을 수 있게: 'Кок-Тобе' → 'Kok-Tobe')
const CYR = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'yo', ж: 'zh', з: 'z', и: 'i', й: 'y', к: 'k', л: 'l', м: 'm',
  н: 'n', о: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'kh', ц: 'ts', ч: 'ch', ш: 'sh', щ: 'shch',
  ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
  // 카자흐어 글자
  ә: 'a', ғ: 'gh', қ: 'q', ң: 'ng', ө: 'o', ұ: 'u', ү: 'u', һ: 'h', і: 'i',
};
export const hasCyrillic = (s) => /[Ѐ-ӿ]/.test(String(s || ''));
export function cyrillicToLatin(s) {
  return String(s || '').split('').map(ch => {
    const lower = ch.toLowerCase();
    if (!(lower in CYR)) return ch;
    const out = CYR[lower];
    return ch !== lower && out ? out[0].toUpperCase() + out.slice(1) : out;
  }).join('');
}

